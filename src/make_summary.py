# الاستخدام (من جذر المشروع):  python src/make_summary.py
import pandas as pd


def fmt(v, digits):
    if pd.isna(v):
        return "n/a"
    return f"{v:.{digits}f}" if isinstance(v, float) else str(v)


def md_table(df, digits=3):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(fmt(v, digits) for v in r) + " |")
    return "\n".join(lines)


def main():
    cv = pd.read_csv("results/cv_bootstrap_ci.csv").drop(columns=["interval_excludes_0"])
    folds = pd.read_csv("results/cv_fold_results.csv").drop(columns=["CNN_epochs"])
    off = pd.read_csv("results/subject_bootstrap_ci.csv").drop(columns=["ci_excludes_0"])
    rec = pd.read_csv("results/error_recall_table.csv", index_col=0).reset_index().rename(columns={"index": "activity"})
    top = pd.read_csv("results/top_confusions.csv")
    acc = pd.read_csv("results/accuracy_ci.csv")
    st = pd.read_csv("results/stat_tests.csv")

    text = "# Results summary (generated by src/make_summary.py)\n\n"
    text += "## Macro-F1 over all 30 subjects (5-fold, 95% subject-level bootstrap intervals)\n\n" + md_table(cv, 4) + "\n\n"
    text += "## Per-fold macro-F1\n\n" + md_table(folds, 4) + "\n\n"
    text += "## Per-class recall (group = unseen subjects, random = random window split)\n\n" + md_table(rec, 3) + "\n\n"
    text += "## Most frequent confusions\n\n" + md_table(top, 3) + "\n\n"
    text += "## Official split (17 fit / 4 validation / 9 test subjects)\n\n" + md_table(off, 4) + "\n"

    text += "\n## Accuracy over all 30 subjects (95% subject-level bootstrap intervals)\n\n" + md_table(acc, 4) + "\n"
    eff_cols = ["hyp", "description", "n_nonzero", "mean_diff", "mean_ci_low", "mean_ci_high",
                "median_diff", "median_ci_low", "median_ci_high", "subjects_positive"]
    p_cols = ["hyp", "p_wilcoxon", "p_wilcoxon_holm", "p_permutation", "p_permutation_holm"]
    text += "\n## Statistical tests (pre-registered in CONTRIBUTIONS.md; unit of analysis: the subject)\n\n"
    text += "Per-subject macro-F1 differences with subject-level bootstrap 95% intervals.\n\n" + md_table(st[eff_cols], 4) + "\n\n"
    text += ("Two-sided p-values. Holm correction covers H1 to H3 only; H4 is exploratory and uncorrected. "
             "Values shown as 0.00000 are below 0.000005.\n\n") + md_table(st[p_cols], 5) + "\n"
    with open("results/results_summary.md", "w", encoding="utf-8") as f:
        f.write(text)
    print("Wrote results/results_summary.md")


if __name__ == "__main__":
    main()
